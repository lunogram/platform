#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: ./etc/bootstrap-env.sh [--force]

Creates local development env files:
  - .env
  - console/.env

By default, existing files are left unchanged.
Use --force to overwrite them.
EOF
}

FORCE=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    -f|--force)
      FORCE=1
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      usage
      exit 1
      ;;
  esac
  shift
done

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BACKEND_ENV_FILE="$ROOT_DIR/.env"
CONSOLE_ENV_FILE="$ROOT_DIR/console/.env"

if [[ ! -d "$ROOT_DIR/console" ]]; then
  echo "console directory not found at $ROOT_DIR/console" >&2
  exit 1
fi

generate_console_signing_key() {
  if ! command -v openssl >/dev/null 2>&1; then
    echo "openssl is required to generate AUTH_CONSOLE_SIGNING_KEY" >&2
    exit 1
  fi

  local key=""
  local line
  while IFS= read -r line; do
    if [[ -z "$key" ]]; then
      key="$line"
    else
      key="${key}\\n${line}"
    fi
  done < <(openssl ecparam -name prime256v1 -genkey -noout)

  if [[ -z "$key" ]]; then
    echo "failed to generate AUTH_CONSOLE_SIGNING_KEY" >&2
    exit 1
  fi

  printf '%s' "$key"
}

write_backend_env() {
  if [[ -f "$BACKEND_ENV_FILE" && "$FORCE" -eq 0 ]]; then
    echo "skip $BACKEND_ENV_FILE (already exists)"
    return
  fi

  local signing_key
  signing_key="$(generate_console_signing_key)"

  cat >"$BACKEND_ENV_FILE" <<EOF
# Generated by ./etc/bootstrap-env.sh for local development.
# Start dependencies with: docker compose -f docker-compose.deps.yml up -d
POSTGRES_MANAGEMENT_URI=postgres://postgres:postgrespw@localhost:5432/management?sslmode=disable
POSTGRES_SUBJECTS_URI=postgres://postgres:postgrespw@localhost:5432/subjects?sslmode=disable
POSTGRES_JOURNEY_URI=postgres://postgres:postgrespw@localhost:5432/journey?sslmode=disable
RBAC_POSTGRES_URI=postgres://postgres:postgrespw@localhost:5432/rbac?sslmode=disable
REDIS_ADDRESS=redis://localhost:6379
NATS_URL=nats://localhost:4222

AUTH_DRIVER=basic
AUTH_BASIC_EMAIL=admin@localhost
AUTH_BASIC_PASSWORD=change-this-development-password
AUTH_BASIC_REGISTRATION=invite_only
AUTH_CONSOLE_SIGNING_KEY=$signing_key

MAIL_CHANNEL=smtp
MAIL_FROM_ADDRESS=no-reply@localhost
MAIL_FROM_NAME=Lunogram
MAIL_SMTP_HOST=localhost
MAIL_SMTP_PORT=1025
MAIL_SMTP_TLS=none

PUBLIC_URL=http://localhost:8080
EOF

  echo "wrote $BACKEND_ENV_FILE"
}

write_console_env() {
  if [[ -f "$CONSOLE_ENV_FILE" && "$FORCE" -eq 0 ]]; then
    echo "skip $CONSOLE_ENV_FILE (already exists)"
    return
  fi

  cat >"$CONSOLE_ENV_FILE" <<'EOF'
VITE_API_BASE_URL=/api
VITE_PROXY_URL=http://localhost:8080
VITE_COURIER_URL=http://localhost:8082
EOF

  echo "wrote $CONSOLE_ENV_FILE"
}

write_backend_env
write_console_env

echo
echo "Done. Next steps:"
echo "  1) docker compose -f docker-compose.deps.yml up -d"
echo "  2) set -a; source .env; set +a"
echo "  3) go run ./cmd/lunogram"
echo "  4) in another terminal: cd console && pnpm install && pnpm dev"
